export function platformProfile(user?: User | null): PlatformAccessProfile | null { return user?.role === 'PLATFORM_ADMIN' ? user.platformAccessProfile || 'SYSTEM_ADMIN' : null; }
export function platformCan(user: User | null | undefined, ...profiles: PlatformAccessProfile[]): boolean { const profile = platformProfile(user); return profile === 'SYSTEM_ADMIN' || (profile !== null && profiles.includes(profile)); }
export function roleName(role: Role, accessProfile?: PlatformAccessProfile | null) {
  if (role === 'PLATFORM_ADMIN') return ({ SYSTEM_ADMIN: '平台系统管理员', OPERATIONS: '平台运营', FINANCE: '平台财务', COMPLIANCE: '平台合规', SECURITY: '平台安全' } as Record<PlatformAccessProfile, string>)[accessProfile || 'SYSTEM_ADMIN'];
  return ({ AGENCY_ADMIN: '代理商', MERCHANT_ADMIN: '商家管理员', STORE_STAFF: '核销员' })[role];
}
